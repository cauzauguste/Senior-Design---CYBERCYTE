@app.post('/simulate/portscan')
async def simulate_portscan(host_id: str = 'host-1', src_ip: str = '10.0.0.5'):
    # simulate many short flows to many dst ports by writing rows
    for p in [22, 80, 443, 8080, 3306, 8081]:
        write_raw_log({'timestamp': time.strftime('%Y-%m-%d %H:%M:%S'), 'host_id': host_id, 'src_ip': src_ip, 'dst_ip': '192.0.2.5', 'event_type': 'flow', 'event_text': f'port={p}', 'bytes_sent': 50, 'bytes_received': 0})
    return {'status': 'ok', 'message': 'portscan simulated'}


@app.post('/simulate/bruteforce')
async def simulate_bruteforce(host_id: str = 'host-ssh', src_ip: str = '10.0.9.9'):
    # write repeated failed login events
    for i in range(40):
        write_raw_log({'timestamp': time.strftime('%Y-%m-%d %H:%M:%S'), 'host_id': host_id, 'src_ip': src_ip, 'dst_ip': '', 'event_type': 'auth_fail', 'event_text': 'failed login', 'bytes_sent': 0, 'bytes_received': 0})
    return {'status': 'ok', 'message': 'bruteforce simulated'}


@app.post('/simulate/exfil')
async def simulate_exfil(host_id: str = 'host-exfil', dst_ip: str = '198.51.100.9'):
    # single large transfer
    write_raw_log({'timestamp': time.strftime('%Y-%m-%d %H:%M:%S'), 'host_id': host_id, 'src_ip': '10.0.1.5', 'dst_ip': dst_ip, 'event_type': 'flow', 'event_text': 'large outbound', 'bytes_sent': 5000000, 'bytes_received': 10})
    return {'status': 'ok', 'message': 'exfil simulated'}


