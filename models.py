# Threat Manager
# -------------------------
class ThreatManager:
    def __init__(self, models: Dict[str, Any]):
        self.models = models
        self.running = False

    async def pull_and_run(self):
        # fetch unprocessed logs
        logs = fetch_unprocessed_logs(limit=200)
        if not logs:
            return
        processed_ids = []
        for r in logs:
            processed_ids.append(r['id'])
            # Basic feature extraction
            features = {
                'bytes_sent': r.get('bytes_sent', 0),
                'bytes_received': r.get('bytes_received', 0),
                'duration': 1
            }
            # Run IsolationForest for simple flow anomalies
            if 'iforest' in self.models:
                out = self.models['iforest'].predict(features)
                if out['anomaly']:
                    write_event('Anomaly: IsolationForest', 'medium', {'score': out['score'], 'log_id': r['id'], 'host': r['host_id']})

            # Run RandomForest network IDS
            if 'netrf' in self.models:
                out = self.models['netrf'].predict(features)
                if out.get('attack'):
                    write_event('Network Attack: RFC', 'high', {'prob': out.get('prob'), 'log_id': r['id']})

            # DeepLog-like sequence detection (if event_text contains sequences)
            if 'deeplog' in self.models:
                seq = r.get('event_text', '').split('|')
                out = self.models['deeplog'].predict(seq)
                if out['anomaly']:
                    write_event('Sequence Anomaly: DeepLog', 'high', {'reason': out.get('reason'), 'log_id': r['id']})

            # LogBERT-like
            if 'logbert' in self.models:
                out = self.models['logbert'].predict(r.get('event_text', ''))
                if out['anomaly']:
                    write_event('Log Semantic Anomaly: LogBERT', 'high', {'keyword': out.get('keyword'), 'log_id': r['id']})

            # Ember-like malware detection (if event_text describes a binary)
            if 'ember' in self.models and 'file_size' in r:
                out = self.models['ember'].predict({'file_size': r.get('file_size'), 'num_imports': r.get('num_imports', 0)})
                if out['malware']:
                    write_event('Malware: EMBER-like', 'critical', {'log_id': r['id']})

        # mark logs processed
        mark_logs_processed(processed_ids)

    async def run_loop(self):
        self.running = True
        while self.running:
            try:
                await self.pull_and_run()
            except Exception as e:
                print('Error in pull_and_run:', e)
            await asyncio.sleep(POLL_INTERVAL_SECONDS)

    def stop(self):
        self.running = False


