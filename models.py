app = FastAPI()
manager: ThreatManager = None


class GenerateEventRequest(BaseModel):
    timestamp: str
    host_id: str
    src_ip: str = ''
    dst_ip: str = ''
    event_type: str
    event_text: str
    bytes_sent: int = 0
    bytes_received: int = 0


class MitigationRequest(BaseModel):
    event_id: int
    manual_override: bool = False


@app.on_event("startup")
async def startup_event():
    global manager
    init_db()
    # instantiate models in a loop
    models = {}
    models['iforest'] = SimpleIsolationForestModel(contamination=0.1)
    models['netrf'] = SimpleRandomForestNetModel()
    models['ember'] = EmberLikeMalwareModel()
    models['deeplog'] = DeepLogLike()
    models['logbert'] = LogBERTLike()
    manager = ThreatManager(models=models)
    # start background loop
    asyncio.create_task(manager.run_loop())


@app.post('/generate_event')
async def generate_event(req: GenerateEventRequest):
    write_raw_log(req.dict())
    return {'status': 'ok', 'message': 'event written to DB'}


@app.post('/detect')
async def detect_now(background_tasks: BackgroundTasks):
    # Trigger immediate run
    if manager is None:
        raise HTTPException(status_code=500, detail='Manager not ready')
    background_tasks.add_task(manager.pull_and_run)
    return {'status': 'ok', 'message': 'detection scheduled'}


@app.get('/events')
async def get_events(limit: int = 50):
    return list_events(limit=limit)


@app.post('/mitigate')
async def mitigate(req: MitigationRequest):
    # fetch event details
    evs = list_events(limit=200)
    ev = next((e for e in evs if e['id'] == req.event_id), None)
    if not ev:
        raise HTTPException(status_code=404, detail='event not found')
    # create prompt based on event
    prompt = f"Event: {ev['name']}. Details: {ev['details']}. Provide a structured mitigation plan in JSON."
    llm_response = await call_llm(prompt)
    # store mitigation as event detail (could be separate table)
    write_event('Mitigation: Proposed', 'info', {'event_id': req.event_id, 'plan': llm_response})
    return {'status': 'ok', 'llm_plan': llm_response}


