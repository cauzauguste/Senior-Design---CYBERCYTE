DB_PATH = "detector_demo.db"
POLL_INTERVAL_SECONDS = 10  # how often ThreatManager pulls new data

# -------------------------
# Database helper (SQLite)
# -------------------------
def init_db():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    # raw_logs: incoming telemetry rows
    c.execute('''
        CREATE TABLE IF NOT EXISTS raw_logs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp TEXT,
            host_id TEXT,
            src_ip TEXT,
            dst_ip TEXT,
            event_type TEXT,
            event_text TEXT,
            bytes_sent INTEGER,
            bytes_received INTEGER,
            processed INTEGER DEFAULT 0
        )
    ''')
    # events: alerts generated by models
    c.execute('''
        CREATE TABLE IF NOT EXISTS events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp TEXT,
            name TEXT,
            severity TEXT,
            details TEXT,
            mitigated INTEGER DEFAULT 0
        )
    ''')
    conn.commit()
    conn.close()


def write_raw_log(row: Dict[str, Any]):
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute('''INSERT INTO raw_logs (timestamp, host_id, src_ip, dst_ip, event_type, event_text, bytes_sent, bytes_received)
                 VALUES (?, ?, ?, ?, ?, ?, ?, ?)''',
              (row.get('timestamp'), row.get('host_id'), row.get('src_ip'), row.get('dst_ip'),
               row.get('event_type'), row.get('event_text'), row.get('bytes_sent', 0), row.get('bytes_received', 0)))
    conn.commit()
    conn.close()


def fetch_unprocessed_logs(limit: int = 100) -> List[Dict[str, Any]]:
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute('SELECT id, timestamp, host_id, src_ip, dst_ip, event_type, event_text, bytes_sent, bytes_received FROM raw_logs WHERE processed = 0 LIMIT ?', (limit,))
    rows = c.fetchall()
    conn.close()
    keys = ['id', 'timestamp', 'host_id', 'src_ip', 'dst_ip', 'event_type', 'event_text', 'bytes_sent', 'bytes_received']
    return [dict(zip(keys, r)) for r in rows]


def mark_logs_processed(ids: List[int]):
    if not ids:
        return
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute(f'UPDATE raw_logs SET processed = 1 WHERE id IN ({",".join(["?"]*len(ids))})', ids)
    conn.commit()
    conn.close()


def write_event(name: str, severity: str, details: Dict[str, Any]):
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute('INSERT INTO events (timestamp, name, severity, details) VALUES (datetime("now"), ?, ?, ?)',
              (name, severity, json.dumps(details)))
    conn.commit()
    conn.close()


def list_events(limit: int = 100) -> List[Dict[str, Any]]:
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute('SELECT id, timestamp, name, severity, details, mitigated FROM events ORDER BY id DESC LIMIT ?', (limit,))
    rows = c.fetchall()
    conn.close()
    keys = ['id', 'timestamp', 'name', 'severity', 'details', 'mitigated']
    return [dict(zip(keys, r)) for r in rows]


